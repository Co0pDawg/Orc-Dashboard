// Builds css/palettes.css and js/palettes.js from dev/palettes.json (`npm run palettes`).
// Each palette keeps its official colours; a text colour that reads under 4.5:1 is moved toward white (dark themes)
// or black (light themes) just far enough to pass, which keeps its hue, and every change is printed.
import {readFileSync, writeFileSync} from "node:fs";
import {luminance, contrast, mix, lift} from "./palette-math.js";

const at = p => new URL(`../${p}`, import.meta.url);
const {palettes} = JSON.parse(readFileSync(at("dev/palettes.json"), "utf8"));
const kebab = k => k.replace(/[A-Z]/g, m => "-" + m.toLowerCase());
const log = [];
const note = (where, key, from, to, bgs) => { if (from !== to) log.push(`${where} ${key}: ${from} -> ${to} (${bgs.map(b => contrast(to, b).toFixed(1)).join("/")}:1)`); };

// Sleek tokens. Status colours keep their hue for fills and borders; their -text twins carry the readable version.
function sleek(v, where){
  const out = {...v}, extreme = luminance(v.bg) < 0.2 ? "#ffffff" : "#000000";
  for (const k of ["accent", "ok", "run", "bad"]) if (!out[k + "Soft"]) out[k + "Soft"] = mix(v.surface, v[k], 0.15);
  const set = (key, base, toward, bgs) => { out[key] = lift(base, toward, bgs); note(where, key, base, out[key], bgs); };
  set("ink", v.ink, extreme, [v.bg, v.surface]);
  set("muted", v.muted, extreme, [v.bg, v.surface]);
  set("accent", v.accent, extreme, [v.bg, v.surface, out.accentSoft]);
  set("okText", v.ok, extreme, [v.bg, v.surface, out.okSoft]);
  set("runText", v.run, extreme, [v.bg, v.surface, out.runSoft]);
  set("badText", v.bad, extreme, [v.bg, v.surface, out.badSoft]);
  return out;
}
// 1337 tokens: text on the terminal panes and the dark red row tint.
function leet(v, where){
  const out = {...v};
  const set = (key, base, toward, bgs) => { out[key] = lift(base, toward, bgs); note(where, key, base, out[key], bgs); };
  set("ink", v.ink, "#ffffff", [v.bg, v.pane]);
  set("dim", v.dim, "#ffffff", [v.bg, v.pane]);
  for (const k of ["green", "lime", "amber"]) set(k, v[k], "#ffffff", [v.bg, v.pane]);
  set("red", v.red, "#ffffff", [v.bg, v.pane, v.redBg]);
  out.onGreen = v.bg; out.bar = out.green;
  return out;
}
const decl = (o, prefix, keys) => keys.map(k => `--${prefix}${kebab(k)}:${o[k]}`).join(";");
const SLEEK = ["bg", "surface", "ink", "muted", "line", "accent", "accentSoft", "ok", "okSoft", "run", "runSoft", "bad", "badSoft", "okText", "runText", "badText"];
const LEET = ["bg", "pane", "ink", "dim", "faint", "green", "lime", "amber", "red", "redBg", "edge", "onGreen", "bar"];

let css = `/* GENERATED by dev/build-palettes.js from dev/palettes.json: do not edit by hand, run \`npm run palettes\`.
   Colour palettes the viewer can pick in Settings. Each overrides the tokens in tokens.css for both layouts:
   the light variant on bare :root, the dark one under the same two guards tokens.css uses. */\n`;
for (const p of palettes){
  const d = sleek(p.dark, `${p.id} dark`), l = p.light ? sleek(p.light, `${p.id} light`) : d, t = leet(p.leet, `${p.id} 1337`);
  const sel = `:root[data-palette="${p.id}"]`;
  css += `/* ${p.name} (${p.licence}) ${p.source}${p.note ? ` - ${p.note}` : ""} */\n`;
  css += `${sel}{${decl(l, "", SLEEK)};${decl(t, "t-", LEET)}}\n`;
  css += `@media (prefers-color-scheme: dark){${sel}:not([data-theme="light"]){${decl(d, "", SLEEK)};color-scheme:dark}}\n`;
  css += `${sel}[data-theme="dark"]{${decl(d, "", SLEEK)};color-scheme:dark}\n`;
}
writeFileSync(at("css/palettes.css"), css);
writeFileSync(at("js/palettes.js"), `// GENERATED by dev/build-palettes.js from dev/palettes.json: do not edit by hand, run \`npm run palettes\`.
/** Colour palettes offered in Settings; the CSS for each is in css/palettes.css. */
export const PALETTES = ${JSON.stringify(palettes.map(({id, name}) => ({id, name})))};
`);
console.log(`${palettes.length} palettes written. Adjusted for contrast (${log.length}):\n` + (log.join("\n") || "none"));
